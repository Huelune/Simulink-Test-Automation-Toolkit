function tests = test_standalone_harness_execution
%TEST_STANDALONE_HARNESS_EXECUTION Static contracts for exported model SUTs.
tests = functiontests(localfunctions);
end

function testDefaultPreservesInternalHarnessMode(testCase)
cfg = st_config();
verifyEqual(testCase, cfg.SystemUnderTestMode, 'INTERNAL_HARNESS');
verifyTrue(testCase, endsWith(string(cfg.StandaloneRunRootDir), ...
    fullfile('result', 'standalone_runs')));
verifyTrue(testCase, endsWith(string(cfg.StandaloneLatestPointer), ...
    fullfile('result', 'standalone_latest.json')));
end

function testSystemUnderTestModeValidation(testCase)
verifyEqual(testCase, ...
    st_resolve_system_under_test_mode(' exported_model '), ...
    'EXPORTED_MODEL');
verifyEqual(testCase, ...
    st_resolve_system_under_test_mode('internal_harness'), ...
    'INTERNAL_HARNESS');
verifyError(testCase, ...
    @() st_resolve_system_under_test_mode('MIXED'), ...
    'simtest:InvalidSystemUnderTestMode');
end

function testExportedModelForcesPerCutAndRejectsBatch(testCase)
CoverageFilterMode = ["OFF";"OFF"];
T = table(CoverageFilterMode);
verifyEqual(testCase, st_resolve_execution_mode( ...
    'AUTO', T, 'EXPORTED_MODEL'), 'PER_CUT');
verifyEqual(testCase, st_resolve_execution_mode( ...
    'PER_CUT', T, 'EXPORTED_MODEL'), 'PER_CUT');
verifyError(testCase, @() st_resolve_execution_mode( ...
    'BATCH', T, 'EXPORTED_MODEL'), ...
    'simtest:StandaloneModelRequiresPerCut');
end

function testStandaloneModelNamesAreStableAndPhaseSpecific(testCase)
No = [1;2];
CUTName = ["Controller CUT";"Controller CUT"];
CUTPath = ["Top/A/Controller CUT";"Top/B/Controller CUT"];
HarnessName = ["Harness";"Harness"];
TestCaseName = ["TC";"TC"];
T = table(No, CUTName, CUTPath, HarnessName, TestCaseName);
first = st_standalone_model_name(T(1,:), 'INITIAL');
verifyEqual(testCase, first, ...
    st_standalone_model_name(T(1,:), 'INITIAL'));
verifyNotEqual(testCase, first, ...
    st_standalone_model_name(T(1,:), 'FINAL'));
verifyNotEqual(testCase, first, ...
    st_standalone_model_name(T(2,:), 'INITIAL'));
verifyTrue(testCase, isvarname(first));
verifyLessThanOrEqual(testCase, numel(first), namelengthmax);
end

