    'st_run_tests_from_exported_harnesses.m'));
update = regexp(source, 'st_update_expected_from_results', 'once');
finalExport = regexp(source, ...
    "st_prepare_standalone_harness_model\([\s\S]*?'FINAL'", 'once');
finalFilter = regexp(source, ...
    "fullfile\(targetDirectory, 'final', 'filters'\)", 'once');
finalRun = regexp(source, 'RUN_FINAL_START', 'once');
verifyTrue(testCase, update < finalExport && ...
    finalExport < finalFilter && finalFilter < finalRun);
verifyGreaterThanOrEqual(testCase, numel(regexp(source, ...
    'restore_filter_session\(session\)', 'match')), 3);
end

