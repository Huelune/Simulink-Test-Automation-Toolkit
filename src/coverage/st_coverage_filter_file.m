function path = st_coverage_filter_file(targetRow, cfg)
%ST_COVERAGE_FILTER_FILE Return the managed CVF path for one Targets row.

identity = struct( ...
    'TopModel', char(cfg.TopModel), ...
    'No', double(targetRow.No), ...
    'CUTPath', char(string(targetRow.CUTPath)), ...
    'TestCaseName', char(string(targetRow.TestCaseName)));
digest = st_hash_value(identity);
path = fullfile(cfg.CoverageFilterDir, char(cfg.TopModel), ...
    ['coverage_' digest(1:20) '.cvf']);
end
