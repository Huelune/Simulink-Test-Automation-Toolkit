function textValue = flatten_sldv_messages(msg)

if isempty(msg)
    textValue = '';
    return;
end

if ischar(msg) || ...
        (isstring(msg) && isscalar(msg))

    textValue = ...
        char(string(msg));

    return;
end

if iscell(msg)
    parts = strings(0,1);

    for i = 1:numel(msg)
        current = ...
            flatten_sldv_messages(msg{i});

        if ~isempty(current)
            parts(end+1,1) = string(current); %#ok<AGROW>
        end
    end

    textValue = ...
        char(strjoin(parts, ' | '));

    return;
end

if ~isstruct(msg)
    textValue = ...
        char(string(msg));

    return;
end

parts = strings(0,1);

for i = 1:numel(msg)
    if isfield(msg, 'msgid') && ...
            ~isempty(msg(i).msgid)

        parts(end+1,1) = ...
            string(msg(i).msgid); %#ok<AGROW>
    end

    if isfield(msg, 'msg') && ...
            ~isempty(msg(i).msg)

        parts(end+1,1) = ...
            string(msg(i).msg); %#ok<AGROW>

    elseif isfield(msg, 'message') && ...
            ~isempty(msg(i).message)

        parts(end+1,1) = ...
            string(msg(i).message); %#ok<AGROW>
    end
end

textValue = ...
    char(strjoin(parts, ' | '));

end


