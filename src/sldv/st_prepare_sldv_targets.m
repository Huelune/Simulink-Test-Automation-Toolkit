function meta = inspect_sldv_data( ...
        dataFile, ownerPath, cutName, tmaxResolution, ...
        harnessInput, ignoreUnexpectedSldvInputs)

loaded = load(dataFile, 'sldvData');

if ~isfield(loaded, 'sldvData') || ...
        ~isstruct(loaded.sldvData)

    error( ...
        'MAT file does not contain a valid sldvData structure: %s', ...
        dataFile);
end

data = loaded.sldvData;

if ~isfield(data, 'ModelInformation') || ...
        ~isfield(data.ModelInformation, 'SubsystemPath')

    error( ...
        'sldvData.ModelInformation.SubsystemPath is missing.');
end

actualPath = ...
    strtrim( ...
        char(string(data.ModelInformation.SubsystemPath)));

if ~same_simulink_path(actualPath, ownerPath)
    error( ...
        'SLDV subsystem mismatch. Expected=%s, Actual=%s', ...
        ownerPath, ...
        actualPath);
end

if ~isfield(data, 'TestCases') || ...
        isempty(data.TestCases)

    error( ...
        'SLDV data contains no TestCases: %s', ...
        dataFile);
end

sourceIndices = zeros(0,1);
endTimes = zeros(0,1);
parameterCounts = zeros(0,1);
scenarioNames = cell(0,1);
originalNames = cell(0,1);
referenceSignature = strings(0,1);
hasReferenceSignature = false;
inputNames = cell(0,1);
inputTypes = cell(0,1);
inputDimensions = cell(0,1);
ignoredInputNames = cell(0,1);

for sourceIndex = 1:numel(data.TestCases)
    tc = data.TestCases(sourceIndex);

    if testcase_has_no_effect(tc)
        continue;
    end

    if ~isfield(tc, 'timeValues') || ...
            isempty(tc.timeValues)

        error( ...
            'SLDV TestCase %d has no timeValues.', ...
            sourceIndex);
    end

    timeValues = double(tc.timeValues(:));

    if any(~isfinite(timeValues)) || ...
            any(timeValues < 0) || ...
            any(diff(timeValues) < 0)

        error( ...
            'SLDV TestCase %d has invalid timeValues.', ...
            sourceIndex);
    end

    [dataset, params] = ...
        sldvsimdata(dataFile, sourceIndex);

    if ~isa(dataset, 'Simulink.SimulationData.Dataset') || ...
            dataset.numElements == 0

        error( ...
            ['SLDV TestCase %d did not produce ' ...
             'a nonempty Dataset.'], ...
            sourceIndex);
    end

    [signature, names, types, dimensions] = ...
        dataset_signature(dataset);

    [selectedIndices, names, ignoredNames] = ...
        st_select_sldv_input_indices( ...
            names, ...
            harnessInput.Names, ...
            ignoreUnexpectedSldvInputs);

    signature = signature(selectedIndices);
    types = types(selectedIndices);
    dimensions = dimensions(selectedIndices);
    ignoredInputNames = unique( ...
        [ignoredInputNames; ignoredNames], ...
        'stable');

    normalizedParams = ...
        st_normalize_sldv_parameters( ...
            params, ...
            sourceIndex);

    validationIteration = ...
        sltest.testmanager.TestIteration;

    st_apply_sldv_parameters( ...
        validationIteration, ...
        params, ...
        sourceIndex);

    if ~hasReferenceSignature
        referenceSignature = signature;
        inputNames = names;
        inputTypes = types;
        inputDimensions = dimensions;
        hasReferenceSignature = true;

    elseif ~isequal(signature, referenceSignature)
        error( ...
            ['SLDV TestCase %d input interface ' ...
             'differs from earlier cases.'], ...
            sourceIndex);
    end

    outputIndex = ...
        numel(sourceIndices) + 1;

    sourceIndices(outputIndex,1) = sourceIndex;
    endTimes(outputIndex,1) = timeValues(end);
    parameterCounts(outputIndex,1) = numel(normalizedParams);
    scenarioNames{outputIndex,1} = ...
        st_scenario_name(cutName, outputIndex);
    originalNames{outputIndex,1} = ...
        testcase_info_name(tc, sourceIndex);
end

if isempty(sourceIndices)
    error( ...
        'SLDV data contains no effective TestCases.');
end

meta = struct();
meta.SourceIndices = sourceIndices;
meta.EndTimes = endTimes;
meta.RawTmax = max(endTimes);
meta.Tmax = st_quantize_sldv_tmax(meta.RawTmax, tmaxResolution);
meta.ParameterCounts = parameterCounts;
meta.ScenarioNames = scenarioNames;
meta.OriginalNames = originalNames;
meta.InputNames = inputNames;
meta.InputTypes = inputTypes;
meta.InputDimensions = inputDimensions;
meta.IgnoredInputNames = ignoredInputNames;

end


function name = testcase_info_name(tc, sourceIndex)

name = sprintf( ...
    'SLDV Test Case %d', ...
    sourceIndex);

if ~isfield(tc, 'info') || ...
        isempty(tc.info) || ...
        ~isstruct(tc.info)

    return;
end

candidateFields = { ...
    'name', ...
    'Name', ...
    'testCaseName', ...
    'TestCaseName', ...
    'label', ...
    'Label'};

for i = 1:numel(candidateFields)
    fieldName = candidateFields{i};

    if isfield(tc.info, fieldName) && ...
            ~isempty(tc.info.(fieldName))

        name = char( ...
            string(tc.info.(fieldName)));

        return;
    end
end

end


function tf = testcase_has_no_effect(tc)

tf = false;

if ~isfield(tc, 'dataNoEffect') || ...
        isempty(tc.dataNoEffect)

    return;
end

values = tc.dataNoEffect;

if ~iscell(values)
    values = {values};
end

hasValue = false;
allNoEffect = true;

for i = 1:numel(values)
    if isempty(values{i})
        continue;
    end

    hasValue = true;
    allNoEffect = ...
        allNoEffect && ...
        all(logical(values{i}(:)));
end

tf = ...
    hasValue && ...
    allNoEffect;

end


function [signature, names, types, dimensions] = ...
        dataset_signature(dataset)

n = dataset.numElements;

signature = strings(n,1);
names = cell(n,1);
types = cell(n,1);
dimensions = cell(n,1);

for i = 1:n
    element = dataset.getElement(i);

    name = strtrim( ...
        char(string(element.Name)));

    if isempty(name)
        error( ...
            'Dataset element %d has an empty Name.', ...
            i);
    end

    names{i} = name;
    value = element;

    if isa(element, 'Simulink.SimulationData.Signal')
        value = element.Values;
    end

    [valueText, valueType, valueDimensions] = ...
        value_signature(value);

    signature(i) = string( ...
        sprintf( ...
            '%s|%s', ...
            name, ...
            valueText));

    types{i} = valueType;
    dimensions{i} = valueDimensions;
end

end


function [text, dataType, dimensions] = value_signature(value)

if isa(value, 'timeseries')
    data = value.Data;
    dims = size(data);

    if ~isempty(value.Time) && ...
            isprop(value, 'IsTimeFirst') && ...
            value.IsTimeFirst && ...
            ~isempty(dims)

        dims = dims(2:end);

    elseif ~isempty(value.Time) && ...
            ~isempty(dims) && ...
            dims(end) == numel(value.Time)

        dims = dims(1:end-1);

    elseif ~isempty(value.Time) && ...
            ~isempty(dims) && ...
            dims(1) == numel(value.Time)

        dims = dims(2:end);
    end

    dataType = value_data_type(data);
    dimensions = normalize_signal_dimensions(dims);

    text = sprintf( ...
        'timeseries|%s|%s', ...
        dataType, ...
        mat2str(dimensions));

elseif istimetable(value)
    data = value.Variables;
    dims = size(data);
    dims = dims(2:end);

    dataType = value_data_type(data);
    dimensions = normalize_signal_dimensions(dims);

    text = sprintf( ...
        'timetable|%s|%s', ...
        dataType, ...
        mat2str(dimensions));

else
    dataType = value_data_type(value);
    dimensions = normalize_signal_dimensions(size(value));

    text = sprintf( ...
        '%s|%s', ...
        dataType, ...
        mat2str(dimensions));
end

end


function type = value_data_type(value)

if isa(value, 'embedded.fi')
    type = 'fixed';

elseif isstruct(value)
    type = 'bus';

else
    type = class(value);
end

end


function dims = normalize_signal_dimensions(dims)

dims = double(dims(:).');

if isempty(dims)
    dims = 1;

elseif all(dims == 1)
    dims = 1;
end

end


function interface = inspect_harness_input_interface( ...
        cfg, ...
        ownerPath, ...
        harnessName)
%INSPECT_HARNESS_INPUT_INTERFACE
% Read the actual runtime input interface from the target Harness Signal
% Editor ActiveScenario Dataset.
%
% This deliberately does not inspect direct CUT Inport blocks.

harnessName = char(harnessName);

st_force_model_stopped(cfg.TopModel);

sltest.harness.load( ...
    ownerPath, ...
    harnessName);

cleanup = onCleanup( ...
    @() close_harness_quiet( ...
        ownerPath, ...
        harnessName)); %#ok<NASGU>

signalEditorBlock = ...
    st_find_signal_editor_block(harnessName);

scenarioName = ...
    strtrim( ...
        char( ...
            get_param( ...
                signalEditorBlock, ...
                'ActiveScenario')));

if isempty(scenarioName)
    error( ...
        'Signal Editor ActiveScenario is empty: %s', ...
        signalEditorBlock);
end

matPath = ...
    st_resolve_data_file( ...
        get_param( ...
            signalEditorBlock, ...
            'Filename'), ...
        cfg.TopModel);

if ~isfile(matPath)
    error( ...
        'Signal Editor data file not found: %s', ...
        matPath);
end

loaded = ...
    load( ...
        matPath, ...
        scenarioName);

if ~isfield(loaded, scenarioName)
    error( ...
        'Active scenario variable not found in MAT file: %s', ...
        scenarioName);
end

scenario = ...
    loaded.(scenarioName);

if ~isa( ...
        scenario, ...
        'Simulink.SimulationData.Dataset') || ...
        scenario.numElements == 0

    error( ...
        ['Harness Signal Editor ActiveScenario must be a nonempty ' ...
         'Simulink.SimulationData.Dataset: %s'], ...
        scenarioName);
end

[~, names, types, dimensions] = ...
    dataset_signature(scenario);

interface = struct();
interface.ScenarioName = scenarioName;
interface.DataFile = canonical_path(matPath);
interface.Names = names;
interface.Types = types;
interface.Dimensions = dimensions;

end


function [sldvDrivenNames, preservedHarnessNames] = ...
        validate_harness_input_interface( ...
        harnessInput, ...
        datasetNames, ...
        datasetTypes, ...
        datasetDimensions, ...
        ignoreUnexpectedSldvInputs)
%VALIDATE_HARNESS_INPUT_INTERFACE
% Validate an SLDV Dataset against the Harness ActiveScenario input
% interface. SLDV inputs must be a subset of the Harness inputs. Harness
% inputs omitted by SLDV are retained from the original ActiveScenario when
% the per-TestCase Signal Editor Dataset is assembled.

harnessNames = ...
    harnessInput.Names;

datasetNames = cellstr(string(datasetNames(:)));

if numel(unique(string(harnessNames(:)))) ~= numel(harnessNames)

    error( ...
        'Harness ActiveScenario contains duplicate input names: [%s]', ...
        strjoin(harnessNames, ', '));
end

[selectedIndices, datasetNames] = ...
    st_select_sldv_input_indices( ...
        datasetNames, ...
        harnessNames, ...
        ignoreUnexpectedSldvInputs);
datasetTypes = datasetTypes(selectedIndices);
datasetDimensions = datasetDimensions(selectedIndices);

for i = 1:numel(datasetNames)

    datasetName = datasetNames{i};
    harnessIndex = find(strcmp(harnessNames, datasetName), 1, 'first');

    if ~strcmpi( ...
            harnessInput.Types{harnessIndex}, ...
            datasetTypes{i})

        error( ...
            ['SLDV Dataset/Harness ActiveScenario data type mismatch at ' ...
             'input %d (%s). Harness=%s, SLDV=%s'], ...
            i, ...
            datasetName, ...
            harnessInput.Types{harnessIndex}, ...
            datasetTypes{i});
    end

    if ~isequal( ...
            harnessInput.Dimensions{harnessIndex}, ...
            datasetDimensions{i})

        error( ...
            ['SLDV Dataset/Harness ActiveScenario dimensions mismatch at ' ...
             'input %d (%s). Harness=%s, SLDV=%s'], ...
            i, ...
            datasetName, ...
            mat2str(harnessInput.Dimensions{harnessIndex}), ...
            mat2str(datasetDimensions{i}));
    end
end

sldvDrivenNames = datasetNames;
preservedHarnessNames = ...
    harnessNames(~ismember(string(harnessNames), string(datasetNames)));

end


function users = collect_signal_editor_data_users(cfg)

harnesses = ...
    sltest.harness.find(cfg.TopModel);

users = ...
    struct( ...
        'Owner', {}, ...
        'Harness', {}, ...
        'DataFile', {}, ...
        'Label', {});

for i = 1:numel(harnesses)
    owner = ...
        char(harnesses(i).ownerFullPath);

    harnessName = ...
        char(harnesses(i).name);

    try
        sltest.harness.load( ...
            owner, ...
            harnessName);

        block = ...
            st_find_signal_editor_block(harnessName);

        matPath = ...
            st_resolve_data_file( ...
                get_param(block, 'Filename'), ...
                cfg.TopModel);

        entry.Owner = owner;
        entry.Harness = harnessName;
        entry.DataFile = canonical_path(matPath);
        entry.Label = [owner '::' harnessName];

        users(end+1) = entry; %#ok<AGROW>

    catch
        % Harnesses without a Signal Editor are not data-file users.
    end

    close_harness_quiet( ...
        owner, ...
        harnessName);
end

end


