function [R, ScenarioR] = st_prepare_sldv_targets(stageSelection)
%ST_PREPARE_SLDV_TARGETS Generate or validate per-target SLDV test data.
% The resulting manifest is consumed by all later workflow stages.
%
% SLDV input-interface validation uses the target Harness Signal Editor
% ActiveScenario Dataset as the source of truth. This is intentional:
% runtime Harness inputs can include upstream/external signals that are not
% represented as direct CUT Inport blocks.

cfg = st_require_runtime_target();
T = st_load_targets(cfg.OnlyEnabled);
if nargin < 1
    stageSelection = [];
end
selection = st_normalize_stage_selection(T, stageSelection);

if ~isfolder(cfg.SldvDir)
    mkdir(cfg.SldvDir);
end

if ~bdIsLoaded(cfg.TopModel)
    load_system(cfg.TopModel);
end
st_force_model_stopped(cfg.TopModel);

n = height(T);
profiles = repmat(empty_profile(), n, 1);

SourceDataFile = strings(n,1);
EffectiveDataFile = strings(n,1);
SldvRunStatus = nan(n,1);
SldvRunMessage = strings(n,1);
SldvRunElapsedSec = nan(n,1);
ScenarioCount = zeros(n,1);
RawTmax = nan(n,1);
Tmax = nan(n,1);
ParameterCount = zeros(n,1);
SldvDrivenInputs = strings(n,1);
PreservedHarnessInputs = strings(n,1);
IgnoredSldvInputs = strings(n,1);
SldvDrivenInputCount = zeros(n,1);
PreservedHarnessInputCount = zeros(n,1);
IgnoredSldvInputCount = zeros(n,1);
AtomicAction = strings(n,1);
Status = strings(n,1);
Message = strings(n,1);
ElapsedSec = zeros(n,1);
Timestamp = strings(n,1);
PreparationAction = selection.Action;
PreparationReason = selection.Reason;

scenarioTargetRow = zeros(0,1);
scenarioNo = zeros(0,1);
scenarioCUTName = strings(0,1);
scenarioMode = strings(0,1);
scenarioSourceIndex = zeros(0,1);
scenarioOriginalName = strings(0,1);
scenarioName = strings(0,1);
scenarioEndTime = zeros(0,1);
scenarioTmax = zeros(0,1);
scenarioParamCount = zeros(0,1);
scenarioStatus = strings(0,1);
scenarioMessage = strings(0,1);

fprintf('\n============================================\n');
fprintf('Prepare Simulink Design Verifier Data\n');
fprintf('============================================\n');

for i = 1:n
    timerValue = tic;
    ownerPath = st_normalize_cut_path(T.CUTPath(i), cfg.TopModel);
    mode = upper(strtrim(char(T.SldvMode(i))));
    if isempty(mode)
        mode = 'OFF';
    end

    profile = empty_profile();
    profile.No = double(T.No(i));
    profile.CUTName = char(T.CUTName(i));
    profile.CUTPath = ownerPath;
    profile.HarnessName = char(T.HarnessName(i));
    profile.TestCaseName = char(T.TestCaseName(i));
    profile.Mode = mode;
    profile.RequestedDataFile = char(T.SldvDataFile(i));
    profile.SourceDataFile = char(T.SldvDataFile(i));

    if ~selection.Run(i)
        try
            profile = st_get_sldv_profile(T(i,:), cfg);
            if ~isfield(profile, 'AtomicAction')
                profile.AtomicAction = 'UNKNOWN';
            end
            SourceDataFile(i) = string(profile_field( ...
                profile, 'SourceDataFile', ''));
            EffectiveDataFile(i) = string(profile_field( ...
                profile, 'EffectiveDataFile', ''));
            SldvRunStatus(i) = profile_field( ...
                profile, 'SldvRunStatus', NaN);
            SldvRunMessage(i) = string(profile_field( ...
                profile, 'SldvRunMessage', ''));
            SldvRunElapsedSec(i) = profile_field( ...
                profile, 'SldvRunElapsedSec', NaN);
            ScenarioCount(i) = numel(profile.ScenarioNames);
            RawTmax(i) = profile_field(profile, 'RawTmax', NaN);
            Tmax(i) = profile_field(profile, 'Tmax', NaN);
            parameterCounts = profile_field( ...
                profile, 'ParameterCounts', []);
            ParameterCount(i) = sum(parameterCounts);
            drivenNames = profile_field( ...
                profile, 'SldvDrivenInputNames', {});
            preservedNames = profile_field( ...
                profile, 'PreservedHarnessInputNames', {});
            ignoredNames = profile_field( ...
                profile, 'IgnoredSldvInputNames', {});
            SldvDrivenInputs(i) = string(strjoin(drivenNames, ', '));
            PreservedHarnessInputs(i) = ...
                string(strjoin(preservedNames, ', '));
            IgnoredSldvInputs(i) = string(strjoin(ignoredNames, ', '));
            SldvDrivenInputCount(i) = numel(drivenNames);
            PreservedHarnessInputCount(i) = numel(preservedNames);
            IgnoredSldvInputCount(i) = numel(ignoredNames);
            AtomicAction(i) = string(profile_field( ...
                profile, 'AtomicAction', 'UNKNOWN'));
            Status(i) = 'CACHED';
            Message(i) = selection.Reason(i);

            [scenarioTargetRow, scenarioNo, scenarioCUTName, ...
                scenarioMode, scenarioSourceIndex, scenarioOriginalName, ...
                scenarioName, scenarioEndTime, scenarioTmax, ...
                scenarioParamCount, scenarioStatus, scenarioMessage] = ...
                append_cached_scenarios(profile, i, T(i,:), ...
                    scenarioTargetRow, scenarioNo, scenarioCUTName, ...
                    scenarioMode, scenarioSourceIndex, ...
                    scenarioOriginalName, scenarioName, scenarioEndTime, ...
                    scenarioTmax, scenarioParamCount, scenarioStatus, ...
                    scenarioMessage);
        catch ME
            Status(i) = 'FAIL';
            Message(i) = "Cached SLDV profile is invalid: " + ...
                string(ME.message);
            profile.ErrorMessage = char(Message(i));
        end

        % CACHED is a stage-reporting state, not a runtime-profile state.
        % Keep the reusable manifest profile successful. Only cache lookup
        % failures are written back as failed profiles.
        if ~strcmp(Status(i), 'CACHED')
            profile.Status = char(Status(i));
            profile.Message = char(Message(i));
        end
        profiles(i) = profile;
        ElapsedSec(i) = toc(timerValue);
        Timestamp(i) = current_timestamp();
        fprintf('[%d/%d] %-6s %s | Mode=%s | %s\n', ...
            i, n, char(Status(i)), char(T.CUTName(i)), mode, ...
            char(Message(i)));
        continue;
    end

    try
        if ~ismember(mode, {'OFF','FILE','GENERATE'})
            error('SldvMode must be OFF, FILE, or GENERATE: %s', mode);
        end

        if strcmp(mode, 'OFF')
            profile.AtomicAction = 'NOT_APPLICABLE';
            AtomicAction(i) = string(profile.AtomicAction);
            profile.ScenarioNames = {st_scenario_name(T.CUTName(i), 1)};
            profile.SourceIndices = [];
            profile.EndTimes = [];
            profile.Tmax = NaN;
            profile.ParameterCounts = 0;

            ScenarioCount(i) = 1;
            ParameterCount(i) = 0;
            Status(i) = 'SKIP';
            Message(i) = 'Legacy single-scenario workflow';

        else
            profile.AtomicAction = ensure_atomic_sldv_cut(cfg, ownerPath);
            AtomicAction(i) = string(profile.AtomicAction);

            % Runtime input interface is defined by the target Harness
            % Signal Editor ActiveScenario, not by direct CUT Inport blocks.
            harnessInput = inspect_harness_input_interface( ...
                cfg, ownerPath, profile.HarnessName);

            profile.HarnessScenarioName = harnessInput.ScenarioName;
            profile.SignalEditorDataFile = harnessInput.DataFile;
            profile.HarnessInputNames = harnessInput.Names;
            profile.HarnessInputTypes = harnessInput.Types;
            profile.HarnessInputDimensions = harnessInput.Dimensions;

            st_log(cfg, 'DEBUG', ...
                '[SLDV %d/%d] Harness ActiveScenario=%s | inputs=[%s]', ...
                i, n, harnessInput.ScenarioName, ...
                strjoin(harnessInput.Names, ', '));

            if strcmp(mode, 'FILE')
                dataFile = resolve_sldv_data_file(T.SldvDataFile(i), cfg);
                SourceDataFile(i) = string(dataFile);
                profile.SourceDataFile = dataFile;
                meta = inspect_sldv_data( ...
                    dataFile, ownerPath, T.CUTName(i), ...
                    cfg.SldvTmaxResolution, harnessInput, ...
                    cfg.IgnoreUnexpectedSldvInputs);

                validate_harness_input_interface( ...
                    harnessInput, ...
                    meta.InputNames, ...
                    meta.InputTypes, ...
                    meta.InputDimensions, ...
                    cfg.IgnoreUnexpectedSldvInputs);

                effectiveFile = dataFile;
            else
                [effectiveFile, runStatus, runMessage, runElapsed, meta] = ...
                    generate_sldv_data( ...
                        cfg, T(i,:), ownerPath, harnessInput);

                SldvRunStatus(i) = runStatus;
                SldvRunMessage(i) = string(runMessage);
                SldvRunElapsedSec(i) = runElapsed;
                profile.SldvRunStatus = runStatus;
                profile.SldvRunMessage = runMessage;
                profile.SldvRunElapsedSec = runElapsed;

                if double(runStatus) ~= 1 || ...
                        isempty(effectiveFile) || ...
                        isempty(meta)

                    error( ...
                        'SLDV generation failed (status=%g): %s', ...
                        double(runStatus), ...
                        runMessage);
                end

                SourceDataFile(i) = string(effectiveFile);
                profile.SourceDataFile = effectiveFile;
            end

            profile.EffectiveDataFile = effectiveFile;
            profile.ScenarioNames = meta.ScenarioNames;
            profile.SourceIndices = meta.SourceIndices;
            profile.OriginalNames = meta.OriginalNames;
            profile.EndTimes = meta.EndTimes;
            profile.RawTmax = meta.RawTmax;
            profile.Tmax = meta.Tmax;
            profile.ParameterCounts = meta.ParameterCounts;
            profile.InputNames = meta.InputNames;
            profile.InputTypes = meta.InputTypes;
            profile.InputDimensions = meta.InputDimensions;
            profile.IgnoreUnexpectedSldvInputs = ...
                logical(cfg.IgnoreUnexpectedSldvInputs);
            profile.IgnoredSldvInputNames = meta.IgnoredInputNames;

            if ~isempty(meta.IgnoredInputNames)
                st_log( ...
                    cfg, ...
                    'WARN', ...
                    ['[SLDV %d/%d] ignoring inputs not present in Harness ' ...
                     'ActiveScenario | inputs=[%s]'], ...
                    i, ...
                    n, ...
                    strjoin(meta.IgnoredInputNames, ', '));
            end

            % An SLDV Dataset may omit inputs that are driven elsewhere in
            % the Harness.  The missing Harness scenario elements are kept
            % when the UT_REQ Dataset is assembled later.
            [sldvDrivenNames, preservedHarnessNames] = ...
                validate_harness_input_interface( ...
                    harnessInput, ...
                    meta.InputNames, ...
                    meta.InputTypes, ...
                    meta.InputDimensions, ...
                    cfg.IgnoreUnexpectedSldvInputs);

            profile.SldvDrivenInputNames = sldvDrivenNames;
            profile.PreservedHarnessInputNames = preservedHarnessNames;
            profile.SldvDrivenInputCount = numel(sldvDrivenNames);
            profile.PreservedHarnessInputCount = numel(preservedHarnessNames);
            profile.IgnoredSldvInputCount = numel(meta.IgnoredInputNames);
            SldvDrivenInputs(i) = string(strjoin(sldvDrivenNames, ', '));
            PreservedHarnessInputs(i) = ...
                string(strjoin(preservedHarnessNames, ', '));
            IgnoredSldvInputs(i) = ...
                string(strjoin(meta.IgnoredInputNames, ', '));
            SldvDrivenInputCount(i) = numel(sldvDrivenNames);
            PreservedHarnessInputCount(i) = numel(preservedHarnessNames);
            IgnoredSldvInputCount(i) = numel(meta.IgnoredInputNames);

            EffectiveDataFile(i) = string(effectiveFile);
            ScenarioCount(i) = numel(meta.ScenarioNames);
            RawTmax(i) = meta.RawTmax;
            Tmax(i) = meta.Tmax;
            ParameterCount(i) = sum(meta.ParameterCounts);
            Status(i) = 'OK';
            Message(i) = sprintf( ...
                ['scenarios=%d, RawTmax=%.17g, Tmax=%.17g, ' ...
                 'sldvInputs=%d, ' ...
                 'preservedHarnessInputs=%d, ignoredSldvInputs=%d'], ...
                ScenarioCount(i), ...
                meta.RawTmax, ...
                meta.Tmax, ...
                SldvDrivenInputCount(i), ...
                PreservedHarnessInputCount(i), ...
                IgnoredSldvInputCount(i));

            for k = 1:numel(meta.ScenarioNames)
                scenarioTargetRow(end+1,1) = i; %#ok<AGROW>
                scenarioNo(end+1,1) = double(T.No(i)); %#ok<AGROW>
                scenarioCUTName(end+1,1) = string(T.CUTName(i)); %#ok<AGROW>
                scenarioMode(end+1,1) = string(mode); %#ok<AGROW>
                scenarioSourceIndex(end+1,1) = meta.SourceIndices(k); %#ok<AGROW>
                scenarioOriginalName(end+1,1) = string(meta.OriginalNames{k}); %#ok<AGROW>
                scenarioName(end+1,1) = string(meta.ScenarioNames{k}); %#ok<AGROW>
                scenarioEndTime(end+1,1) = meta.EndTimes(k); %#ok<AGROW>
                scenarioTmax(end+1,1) = meta.Tmax; %#ok<AGROW>
                scenarioParamCount(end+1,1) = meta.ParameterCounts(k); %#ok<AGROW>
                scenarioStatus(end+1,1) = 'OK'; %#ok<AGROW>
                scenarioMessage(end+1,1) = ''; %#ok<AGROW>
            end
        end

    catch ME
        Status(i) = 'FAIL';
        Message(i) = string(ME.message);
        profile.ErrorMessage = ME.message;

        st_log( ...
            cfg, ...
            'ERROR', ...
            '[SLDV %d/%d] %s', ...
            i, ...
            n, ...
            ME.message);
    end

    profile.Status = char(Status(i));
    profile.Message = char(Message(i));
    profiles(i) = profile;
    ElapsedSec(i) = toc(timerValue);
    Timestamp(i) = current_timestamp();

    fprintf( ...
        '[%d/%d] %-4s %s | Mode=%s | %s\n', ...
        i, ...
        n, ...
        char(Status(i)), ...
        char(T.CUTName(i)), ...
        mode, ...
        char(Message(i)));
end

% Signal Editor MAT ownership is checked only after every target data file
% has passed its source-side validation. This stage does not modify models.
checkSharedSignalEditorDataFile = ...
    isfield(cfg, 'CheckSharedSignalEditorDataFile') && ...
    logical(cfg.CheckSharedSignalEditorDataFile);

executedSldvRows = selection.Run & ~strcmp(T.SldvMode, 'OFF');
if ~any(Status == 'FAIL') && ...
        any(executedSldvRows) && ...
        checkSharedSignalEditorDataFile
    usersReady = false;

    try
        users = collect_signal_editor_data_users(cfg);
        usersReady = true;

    catch ME
        users = [];
        affected = find(executedSldvRows);

        for j = affected(:).'
            [Status, Message, profiles, scenarioStatus, scenarioMessage] = ...
                mark_target_failure( ...
                    j, ...
                    ME.message, ...
                    Status, ...
                    Message, ...
                    profiles, ...
                    scenarioTargetRow, ...
                    scenarioStatus, ...
                    scenarioMessage);
        end
    end

    if usersReady
        for i = find(executedSldvRows).'
            try
                [matPath, matchingUsers] = ...
                    target_signal_editor_data_file( ...
                        users, ...
                        profiles(i).CUTPath, ...
                        profiles(i).HarnessName);

                profiles(i).SignalEditorDataFile = matPath;

                if numel(matchingUsers) > 1
                    error( ...
                        ['Signal Editor MAT file is shared by multiple ' ...
                         'harnesses: %s | %s'], ...
                        matPath, ...
                        strjoin(matchingUsers, ', '));
                end

            catch ME
                [Status, Message, profiles, scenarioStatus, scenarioMessage] = ...
                    mark_target_failure( ...
                        i, ...
                        ME.message, ...
                        Status, ...
                        Message, ...
                        profiles, ...
                        scenarioTargetRow, ...
                        scenarioStatus, ...
                        scenarioMessage);
            end
        end
    end

elseif ~any(Status == 'FAIL') && any(executedSldvRows)
    st_log(cfg, 'INFO', ...
        ['Signal Editor MAT sharing check skipped ' ...
         '(cfg.CheckSharedSignalEditorDataFile=false)']);
end

manifest = struct();
manifest.Version = 4;
manifest.TopModel = cfg.TopModel;
manifest.ManagementExcel = cfg.ManagementExcel;
manifest.CreatedAt = char(current_timestamp());
manifest.Profiles = profiles;
save_manifest_atomic(cfg.SldvManifestFile, manifest);

R = table( ...
    T.No, ...
    T.CUTName, ...
    T.CUTPath, ...
    T.HarnessName, ...
    T.TestCaseName, ...
    T.SldvMode, ...
    SourceDataFile, ...
    EffectiveDataFile, ...
    SldvRunStatus, ...
    SldvRunMessage, ...
    SldvRunElapsedSec, ...
    ScenarioCount, ...
    RawTmax, ...
    Tmax, ...
    ParameterCount, ...
    SldvDrivenInputs, ...
    PreservedHarnessInputs, ...
    IgnoredSldvInputs, ...
    SldvDrivenInputCount, ...
    PreservedHarnessInputCount, ...
    IgnoredSldvInputCount, ...
    AtomicAction, ...
    PreparationAction, ...
    PreparationReason, ...
    Status, ...
    Message, ...
    ElapsedSec, ...
    Timestamp, ...
    'VariableNames', { ...
        'No', ...
        'CUTName', ...
        'CUTPath', ...
        'HarnessName', ...
        'TestCaseName', ...
        'SldvMode', ...
        'SourceDataFile', ...
        'EffectiveDataFile', ...
        'SldvRunStatus', ...
        'SldvRunMessage', ...
        'SldvRunElapsedSec', ...
        'ScenarioCount', ...
        'RawTmax', ...
        'Tmax', ...
        'ParameterCount', ...
        'SldvDrivenInputs', ...
        'PreservedHarnessInputs', ...
        'IgnoredSldvInputs', ...
        'SldvDrivenInputCount', ...
        'PreservedHarnessInputCount', ...
        'IgnoredSldvInputCount', ...
        'AtomicAction', ...
        'PreparationAction', ...
        'PreparationReason', ...
        'Status', ...
        'Message', ...
        'ElapsedSec', ...
        'Timestamp'});

ScenarioR = table( ...
    scenarioTargetRow, ...
    scenarioNo, ...
    scenarioCUTName, ...
    scenarioMode, ...
    scenarioSourceIndex, ...
    scenarioOriginalName, ...
    scenarioName, ...
    scenarioEndTime, ...
    scenarioTmax, ...
    scenarioParamCount, ...
    scenarioStatus, ...
    scenarioMessage, ...
    'VariableNames', { ...
        'TargetRow', ...
        'No', ...
        'CUTName', ...
        'SldvMode', ...
        'SourceIndex', ...
        'OriginalName', ...
        'ScenarioName', ...
        'OriginalEndTime', ...
        'Tmax', ...
        'ParameterCount', ...
        'Status', ...
        'Message'});

st_write_result('SldvGenerationResult', R);
st_write_result('SldvScenarioResult', ScenarioR);

end


function profile = empty_profile()

profile = struct( ...
    'No', NaN, ...
    'CUTName', '', ...
    'CUTPath', '', ...
    'HarnessName', '', ...
    'TestCaseName', '', ...
    'Mode', 'OFF', ...
    'RequestedDataFile', '', ...
    'SourceDataFile', '', ...
    'EffectiveDataFile', '', ...
    'SignalEditorDataFile', '', ...
    'SldvRunStatus', NaN, ...
    'SldvRunMessage', '', ...
    'SldvRunElapsedSec', NaN, ...
    'ScenarioNames', {{}}, ...
    'SourceIndices', [], ...
    'OriginalNames', {{}}, ...
    'EndTimes', [], ...
    'RawTmax', NaN, ...
    'Tmax', NaN, ...
    'ParameterCounts', [], ...
    'InputNames', {{}}, ...
    'InputTypes', {{}}, ...
    'InputDimensions', {{}}, ...
    'HarnessScenarioName', '', ...
    'HarnessInputNames', {{}}, ...
    'HarnessInputTypes', {{}}, ...
    'HarnessInputDimensions', {{}}, ...
    'IgnoreUnexpectedSldvInputs', false, ...
    'SldvDrivenInputNames', {{}}, ...
    'PreservedHarnessInputNames', {{}}, ...
    'IgnoredSldvInputNames', {{}}, ...
    'SldvDrivenInputCount', 0, ...
    'PreservedHarnessInputCount', 0, ...
    'IgnoredSldvInputCount', 0, ...
    'AtomicAction', '', ...
    'Status', '', ...
    'Message', '', ...
    'ErrorMessage', '');

end


function [status, message, profiles, scenarioStatus, scenarioMessage] = ...
        mark_target_failure( ...
            targetIndex, ...
            errorMessage, ...
            status, ...
            message, ...
            profiles, ...
            scenarioTargetRow, ...
            scenarioStatus, ...
            scenarioMessage)

status(targetIndex) = 'FAIL';
message(targetIndex) = string(errorMessage);
profiles(targetIndex).Status = 'FAIL';
profiles(targetIndex).Message = errorMessage;
profiles(targetIndex).ErrorMessage = errorMessage;

scenarioAffected = scenarioTargetRow == targetIndex;
scenarioStatus(scenarioAffected) = 'FAIL';
scenarioMessage(scenarioAffected) = string(errorMessage);

end


function validate_subsystem_cut(ownerPath)

if ~strcmp(get_param(ownerPath, 'BlockType'), 'SubSystem')
    error( ...
        'SLDV mode requires a Subsystem CUT: %s', ...
        ownerPath);
end

end


function action = ensure_atomic_sldv_cut(cfg, ownerPath)

validate_subsystem_cut(ownerPath);

if strcmp(get_param(ownerPath, 'TreatAsAtomicUnit'), 'on')
    action = 'ALREADY_ATOMIC';
    return;
end

if ~isfield(cfg, 'AutoConvertSldvTargetsToAtomic') || ...
        ~cfg.AutoConvertSldvTargetsToAtomic

    error( ...
        ['SLDV FILE/GENERATE requires an atomic subsystem ' ...
         '(TreatAsAtomicUnit=on), and automatic conversion is disabled: %s'], ...
        ownerPath);
end

set_param( ...
    ownerPath, ...
    'TreatAsAtomicUnit', ...
    'on');

action = 'CONVERTED';

st_log( ...
    cfg, ...
    'INFO', ...
    ['[SLDV] Converted target to an atomic Subsystem and kept the change ' ...
     '| CUT=%s'], ...
    ownerPath);

end


function fullPath = resolve_sldv_data_file(value, cfg)

textValue = strtrim(char(string(value)));

if isempty(textValue)
    error( ...
        'SldvDataFile is required when SldvMode=FILE.');
end

fileObj = java.io.File(textValue);

if fileObj.isAbsolute()
    fullPath = char(fileObj.getCanonicalPath());
else
    fullPath = char( ...
        java.io.File( ...
            fileparts(cfg.ManagementExcel), ...
            textValue).getCanonicalPath());
end

if ~isfile(fullPath)
    error( ...
        'SLDV data file not found: %s', ...
        fullPath);
end

end


function [latestFile, status, message, runElapsed, meta] = ...
        generate_sldv_data( ...
            cfg, ...
            targetRow, ...
            ownerPath, ...
            harnessInput)

targetId = safe_target_id(targetRow.No, targetRow.CUTName);
targetDir = fullfile(cfg.SldvDir, targetId);

if ~isfolder(targetDir)
    mkdir(targetDir);
end

stagingDir = tempname(targetDir);
mkdir(stagingDir);

cleanup = onCleanup( ...
    @() cleanup_staging_dir(stagingDir)); %#ok<NASGU>

modelOptions = sldvoptions(cfg.TopModel);
opts = modelOptions.deepCopy;
opts.Mode = 'TestGeneration';
opts.OutputDir = stagingDir;
opts.MakeOutputFilesUnique = 'off';
opts.DataFileName = 'candidate_sldvdata';
opts.SaveReport = 'off';
opts.SaveHarnessModel = 'off';

st_log( ...
    cfg, ...
    'INFO', ...
    '[SLDV] sldvrun start | CUT=%s', ...
    ownerPath);

runTimer = tic;

try
    [status, files, msg] = ...
        sldvrun(ownerPath, opts, false);

    runElapsed = toc(runTimer);
    message = flatten_sldv_messages(msg);

catch ME
    runElapsed = toc(runTimer);
    status = 0;
    files = struct();
    message = ME.message;
end

st_log( ...
    cfg, ...
    'INFO', ...
    '[SLDV] sldvrun returned | CUT=%s | Status=%g', ...
    ownerPath, ...
    double(status));

latestFile = '';
meta = [];

if double(status) ~= 1
    return;
end

if ~isstruct(files) || ...
        ~isfield(files, 'DataFile') || ...
        isempty(files.DataFile)

    message = append_message( ...
        message, ...
        'SLDV generation returned no valid DataFile.');

    return;
end

candidateFile = resolve_generated_data_file( ...
    files.DataFile, ...
    stagingDir);

if isempty(candidateFile)
    message = append_message( ...
        message, ...
        sprintf( ...
            'SLDV generation DataFile does not exist: %s', ...
            char(string(files.DataFile))));

    return;
end

try
    meta = inspect_sldv_data( ...
        candidateFile, ...
        ownerPath, ...
        targetRow.CUTName, ...
        cfg.SldvTmaxResolution, ...
        harnessInput, ...
        cfg.IgnoreUnexpectedSldvInputs);

    validate_harness_input_interface( ...
        harnessInput, ...
        meta.InputNames, ...
        meta.InputTypes, ...
        meta.InputDimensions, ...
        cfg.IgnoreUnexpectedSldvInputs);

    latestFile = ...
        fullfile(targetDir, 'latest_sldvdata.mat');

    temporaryLatest = ...
        [latestFile '.tmp'];

    if isfile(temporaryLatest)
        delete(temporaryLatest);
    end

    copyfile( ...
        candidateFile, ...
        temporaryLatest, ...
        'f');

